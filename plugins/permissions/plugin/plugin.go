// Package plugin is the build-time integration for the Drift permissions
// plugin: permissions that no other plugin provides (contacts, calendar,
// microphone, photos), for apps whose own native code or SDKs use them.
//
// Wire into a project by adding to drift.yaml, with a section for each
// permission the app uses:
//
//	plugins:
//	  - package: github.com/go-drift/drift/plugins/permissions/plugin
//	    config:
//	      contacts:
//	        description: Finds friends who already use the app.
//	      photos:
//	        description: Picks a profile photo.
//
// Each description is the text iOS shows when asking for the permission
// (its usage string); App Review rejects vague ones. A section adds the
// permission to the Android manifest and the usage string to Info.plist;
// permissions without a section are not declared and their calls fail
// with platform.ErrPermissionNotRegistered.
//
// The Go API is github.com/go-drift/drift/plugins/permissions/runtime.
//
// # Platform support
//
// iOS (Xcode 16+), xtool and Android.
package plugin

import (
	"embed"
	"fmt"
	"strconv"
	"strings"

	driftplugin "github.com/go-drift/drift/pkg/plugin"
)

//go:embed ios
var iosSources embed.FS

//go:embed android
var androidSources embed.FS

// androidPackage is the Kotlin package of the plugin's Android sources.
const androidPackage = "com.drift.plugin.permissions"

// Config is the permissions plugin's drift.yaml config block: one optional
// section per permission.
type Config struct {
	Contacts   *Kind `yaml:"contacts,omitempty"`
	Calendar   *Kind `yaml:"calendar,omitempty"`
	Microphone *Kind `yaml:"microphone,omitempty"`
	Photos     *Kind `yaml:"photos,omitempty"`
}

// Kind enables one permission.
type Kind struct {
	// Description is why the app needs the permission, shown by iOS in
	// the permission prompt.
	Description string `yaml:"description" drift:"required"`
}

// kind is what one permission declares on each platform.
type kind struct {
	name string
	cfg  *Kind
	// iosKeys are the Info.plist usage strings the kind needs.
	iosKeys []string
	// android are the manifest permissions, each up to maxSDK when set.
	android []androidPermission
}

type androidPermission struct {
	name   string
	maxSDK int
}

func (c Config) kinds() []kind {
	return []kind{
		{"contacts", c.Contacts, []string{"NSContactsUsageDescription"},
			[]androidPermission{{name: "android.permission.READ_CONTACTS"}}},
		// iOS 17 asks with the full-access string, iOS 16 with the other.
		{"calendar", c.Calendar, []string{"NSCalendarsFullAccessUsageDescription", "NSCalendarsUsageDescription"},
			[]androidPermission{{name: "android.permission.READ_CALENDAR"}}},
		{"microphone", c.Microphone, []string{"NSMicrophoneUsageDescription"},
			[]androidPermission{{name: "android.permission.RECORD_AUDIO"}}},
		// READ_MEDIA_IMAGES replaced READ_EXTERNAL_STORAGE in API 33.
		{"photos", c.Photos, []string{"NSPhotoLibraryUsageDescription"},
			[]androidPermission{
				{name: "android.permission.READ_MEDIA_IMAGES"},
				{name: "android.permission.READ_EXTERNAL_STORAGE", maxSDK: 32},
			}},
	}
}

type permissions struct{}

func (permissions) Name() string { return "permissions" }

func (permissions) Build(ctx *driftplugin.BuildCtx, cfg Config) error {
	var enabled []string
	for _, k := range cfg.kinds() {
		if k.cfg == nil {
			continue
		}
		if strings.TrimSpace(k.cfg.Description) == "" {
			return fmt.Errorf("permissions: %s.description must not be empty", k.name)
		}
		enabled = append(enabled, k.name)
		for _, key := range k.iosKeys {
			ctx.IOS.Info.SetString(key, k.cfg.Description)
		}
		for _, p := range k.android {
			if p.maxSDK > 0 {
				ctx.Android.Manifest.AddPermissionMaxSDK(p.name, p.maxSDK)
			} else {
				ctx.Android.Manifest.AddPermission(p.name)
			}
		}
	}
	if len(enabled) == 0 {
		return fmt.Errorf("permissions: configure at least one of contacts, calendar, microphone, photos")
	}

	ctx.IOS.Sources.AddFS("Permissions", iosSources, "ios")
	ctx.IOS.Sources.AddFile("Permissions", "PermissionsConfig.swift", []byte(swiftConfig(enabled)))
	ctx.IOS.Plugin("DriftPermissionsPlugin")

	ctx.Android.Sources.AddFS(androidPackage, androidSources, "android")
	ctx.Android.Sources.AddFile(androidPackage, "PermissionsConfig.kt", []byte(kotlinConfig(enabled)))
	ctx.Android.Plugin(androidPackage + ".DriftPermissionsPlugin")
	return nil
}

// swiftConfig and kotlinConfig list the enabled kinds, which the native
// plugin registers.
func swiftConfig(kinds []string) string {
	return "// Code generated by the Drift permissions plugin. DO NOT EDIT.\n\n" +
		"enum PermissionsConfig {\n" +
		"    static let kinds: Set<String> = [" + quoted(kinds) + "]\n" +
		"}\n"
}

func kotlinConfig(kinds []string) string {
	return "// Code generated by the Drift permissions plugin. DO NOT EDIT.\n" +
		"package " + androidPackage + "\n\n" +
		"internal object PermissionsConfig {\n" +
		"    val kinds: Set<String> = setOf(" + quoted(kinds) + ")\n" +
		"}\n"
}

func quoted(names []string) string {
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = strconv.Quote(n)
	}
	return strings.Join(q, ", ")
}

// Plugin is the binding the generated bridge picks up.
var Plugin driftplugin.Plugin[Config] = permissions{}
