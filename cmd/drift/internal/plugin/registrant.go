// emitDidReceiveRemoteNotification runs Drift's own notification dispatch,
// then hands the plugin handlers to
// DriftPluginCoordinator.dispatchBackgroundFetch, which owns the lock +
// timer + once-only scaffold and merges the plugins' results. With no plugin
// handlers the coordinator reports .newData, Drift's historical result.
//
// Keeping the scaffold in the hand-written coordinator means the
// race-condition logic lives in one file the swift-test harness exercises
// directly, and the codegen stays one closure per registered symbol.
func emitDidReceiveRemoteNotification(symbols []string) string {
	var b strings.Builder
	b.WriteString("    static func didReceiveRemoteNotification(\n")
	b.WriteString("        application: UIApplication,\n")
	b.WriteString("        userInfo: [AnyHashable: Any],\n")
	b.WriteString("        completionHandler: @escaping (UIBackgroundFetchResult) -> Void\n")
	b.WriteString("    ) {\n")
	b.WriteString("        NotificationHandler.handleRemoteNotification(userInfo, isForeground: application.applicationState == .active)\n")
	if len(symbols) == 0 {
		b.WriteString("        let handlers: [DriftPluginCoordinator.BackgroundFetchHandler] = []\n")
	} else {
		b.WriteString("        let handlers: [DriftPluginCoordinator.BackgroundFetchHandler] = [\n")
		for _, sym := range symbols {
			fmt.Fprintf(&b, "            { userInfo, completion in %s(userInfo: userInfo, completion: completion) },\n", sym)
		}
		b.WriteString("        ]\n")
	}
	b.WriteString("        DriftPluginCoordinator.dispatchBackgroundFetch(\n")
	b.WriteString("            userInfo: userInfo,\n")
	b.WriteString("            handlers: handlers,\n")
	b.WriteString("            completionHandler: completionHandler\n")
	b.WriteString("        )\n")
	b.WriteString("    }\n")
	return b.String()
}

// EnsureRunnerSupport writes the namespace-isolated com.drift.runner.* support
// files that the runtime needs. On Android, this writes DriftPluginHost.kt
// and MethodHandler.kt so ejected projects (where scaffold.WriteAndroid skips
// these) still have them. On iOS and xtool, this is a no-op: the support
// files live under Runner/ and ride the synchronized-group template.
func EnsureRunnerSupport(buildDir, platform string) ([]string, error) {
	switch platform {
	case "android":
		return ensureAndroidRunnerSupport(buildDir)
	case "ios", "xtool":
		return ensureIOSRunnerSupport(buildDir, platform)
	default:
		return nil, fmt.Errorf("EnsureRunnerSupport: unknown platform %q", platform)
	}
}

// IOSRunnerSupportFiles are the hand-written Swift files the generated
// DriftPluginRegistrant.swift depends on. The managed scaffold already
// copies them with the rest of the iOS templates; EnsureRunnerSupport also
// writes them so ejected projects, whose sources were copied at eject time,
// keep compiling when the generated registrant starts referencing them.
var IOSRunnerSupportFiles = []string{"DriftPluginCoordinator.swift"}

func ensureIOSRunnerSupport(buildDir, platform string) ([]string, error) {
	dir := iosRunnerSourcesDir(buildDir, platform)
	var changed []string
	for _, name := range IOSRunnerSupportFiles {
		content, err := templates.ReadFile("ios/" + name)
		if err != nil {
			return changed, fmt.Errorf("read ios/%s: %w", name, err)
		}
		paths, err := writeIfDifferentSingle(filepath.Join(dir, name), content)
		if err != nil {
			return changed, err
		}
		changed = append(changed, paths...)
	}
	return changed, nil
}

// iosRunnerSourcesDir is where the app target's Swift sources live:
// Runner/ for xcodeproj builds (managed and ejected), Sources/Runner/ for
// xtool.
func iosRunnerSourcesDir(buildDir, platform string) string {
	if platform == "xtool" {
		return filepath.Join(buildDir, "Sources", "Runner")
	}
	return filepath.Join(buildDir, "Runner")
}

func ensureAndroidRunnerSupport(buildDir string) ([]string, error) {
	root := filepath.Join(buildDir, "app", "src", "main", "java", "com", "drift", "runner")
	var changed []string
	for _, f := range AndroidRunnerSupportFiles {
		content, err := templates.ReadFile(f.TemplatePath)
		if err != nil {
			return changed, fmt.Errorf("read %s: %w", f.TemplatePath, err)
		}
		dest := filepath.Join(root, f.Name)
		paths, err := writeIfDifferentSingle(dest, content)
		if err != nil {
			return changed, err
		}
		changed = append(changed, paths...)
	}
	return changed, nil
}

func writeIfDifferentSingle(path string, content []byte) ([]string, error) {
	existing, err := os.ReadFile(path)
	if err == nil && bytes.Equal(existing, content) {
		return nil, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return nil, fmt.Errorf("mkdir for %s: %w", path, err)
	}
	if err := os.WriteFile(path, content, 0o644); err != nil {
		return nil, fmt.Errorf("write %s: %w", path, err)
	}
	return []string{path}, nil
}
