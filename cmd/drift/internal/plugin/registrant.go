// AndroidRunnerSupportFiles names the templates that EnsureRunnerSupport
// writes into an ejected Android project's `com.drift.runner` package: the
// plugin API and the plugin lifecycle owner. They are the exact same bytes
// scaffold.WriteAndroid copies during a fresh scaffold; keeping a single
// source of truth here prevents drift between the two. (Earlier the two
// surfaces carried duplicated Kotlin source and the MethodHandler signature
// drifted, breaking every Android build that re-applied EnsureRunnerSupport
// after scaffold.)
var AndroidRunnerSupportFiles = []struct {
	Name         string
	TemplatePath string
}{
	{"DriftPluginHost.kt", "android/runner/DriftPluginHost.kt"},
	{"DriftPlugin.kt", "android/runner/DriftPlugin.kt"},
	{"DriftActivityBinding.kt", "android/runner/DriftActivityBinding.kt"},
	{"DriftPlugins.kt", "android/runner/DriftPlugins.kt"},
	{"DriftMethodHandler.kt", "android/runner/DriftMethodHandler.kt"},
	{"DriftPermission.kt", "android/runner/DriftPermission.kt"},
	{"DriftPlatformView.kt", "android/runner/DriftPlatformView.kt"},
	{"DriftActivityResult.kt", "android/runner/DriftActivityResult.kt"},
	{"DriftJsonCodec.kt", "android/runner/DriftJsonCodec.kt"},
}

// WriteRegistrant generates DriftPluginRegistrant for the target platform and
// plans it into cs at buildDir's fixed runtime-runner path. It only lists
// the configured plugin classes, in drift.yaml order; the hand-written
// DriftPlugins support file drives their lifecycle and the app templates
// keep Drift's own event handling. With no plugins the list is empty, so
// the call site always resolves.
func WriteRegistrant(cs *mutate.Changeset, buildDir, platform string, ops []protocol.Op) ([]string, error) {
	switch platform {
	case "android":
		dest := filepath.Join(buildDir, "app", "src", "main", "java", "com", "drift", "runner", "DriftPluginRegistrant.kt")
		return planFile(cs, dest, []byte(androidRegistrant(ops)))
	case "ios", "xtool":
		dest := filepath.Join(iosRunnerSourcesDir(buildDir, platform), "DriftPluginRegistrant.swift")
		return planFile(cs, dest, []byte(iosRegistrant(ops)))
	default:
		return nil, fmt.Errorf("WriteRegistrant: unknown platform %q", platform)
	}
}

func androidRegistrant(ops []protocol.Op) string {
	var b strings.Builder
	b.WriteString("// Code generated by Drift plugin pipeline. DO NOT EDIT.\n")
	b.WriteString("package com.drift.runner\n\n")
	b.WriteString("internal object DriftPluginRegistrant {\n")
	b.WriteString("    /** Creates one instance of every configured plugin, in drift.yaml order. */\n")
	b.WriteString("    fun makePlugins(): List<DriftPluginEntry> = listOf(\n")
	for _, op := range ops {
		if p, ok := op.(*protocol.OpAndroidPlugin); ok {
			fmt.Fprintf(&b, "        DriftPluginEntry(%q, %t, %s()),\n", p.PluginID(), firstParty(p), p.Class)
		}
	}
	b.WriteString("    )\n")
	b.WriteString("}\n")
	return b.String()
}

func iosRegistrant(ops []protocol.Op) string {
	var plugins []*protocol.OpIOSPlugin
	for _, op := range ops {
		if p, ok := op.(*protocol.OpIOSPlugin); ok {
			plugins = append(plugins, p)
		}
	}
	var b strings.Builder
	b.WriteString("// Code generated by Drift plugin pipeline. DO NOT EDIT.\n\n")
	b.WriteString("import DriftPluginAPI\n")
	imported := map[string]bool{}
	for _, p := range plugins {
		if module := mutate.PluginModule(p.PluginID()); !imported[module] {
			imported[module] = true
			fmt.Fprintf(&b, "import %s\n", module)
		}
	}
	b.WriteString("\nenum DriftPluginRegistrant {\n")
	b.WriteString("    /// Creates one instance of every configured plugin, in drift.yaml order.\n")
	b.WriteString("    static func makePlugins() -> [DriftPluginEntry] {\n")
	if len(plugins) == 0 {
		b.WriteString("        return []\n")
	} else {
		b.WriteString("        return [\n")
		for _, p := range plugins {
			fmt.Fprintf(&b, "            DriftPluginEntry(name: %q, firstParty: %t, plugin: %s.%s()),\n",
				p.PluginID(), firstParty(p), mutate.PluginModule(p.PluginID()), p.Class)
		}
		b.WriteString("        ]\n")
	}
	b.WriteString("    }\n")
	b.WriteString("}\n")
	return b.String()
}

// firstParty reports whether op's plugin ships in the drift module, the
// only plugins that may use Drift's reserved drift/ channel names.
func firstParty(op protocol.Op) bool {
	return strings.HasPrefix(op.PluginPackage(), protocol.DriftModulePath+"/plugins/")
}

// EnsureRunnerSupport plans the Drift-owned plugin support files (the
// plugin API and the plugin lifecycle owner) into cs, so ejected projects,
// whose sources were copied once at eject time, stay in step with the
// generated registrant. Managed builds already have identical copies from the
// scaffold.
func EnsureRunnerSupport(cs *mutate.Changeset, buildDir, platform string) ([]string, error) {
	switch platform {
	case "android":
		return ensureAndroidRunnerSupport(cs, buildDir)
	case "ios", "xtool":
		return ensureIOSRunnerSupport(cs, buildDir, platform)
	default:
		return nil, fmt.Errorf("EnsureRunnerSupport: unknown platform %q", platform)
	}
}

// IOSRunnerSupportFiles are the hand-written Swift files, relative to the
// ios template dir and to the app's source dir, that drive plugins from the
// app target. (The plugin API itself lives in the Drift/Plugins package,
// which Apply regenerates.)
var IOSRunnerSupportFiles = []string{
	"DriftPlugins.swift",
}

func ensureIOSRunnerSupport(cs *mutate.Changeset, buildDir, platform string) ([]string, error) {
	dir := iosRunnerSourcesDir(buildDir, platform)
	var changed []string
	for _, name := range IOSRunnerSupportFiles {
		content, err := templates.ReadFile("ios/" + name)
		if err != nil {
			return changed, fmt.Errorf("read ios/%s: %w", name, err)
		}
		paths, err := planFile(cs, filepath.Join(dir, name), content)
		if err != nil {
			return changed, err
		}
		changed = append(changed, paths...)
	}
	return changed, nil
}

// iosRunnerSourcesDir is where the app target's Swift sources live:
// Runner/ for xcodeproj builds (managed and ejected), Sources/Runner/ for
// xtool.
func iosRunnerSourcesDir(buildDir, platform string) string {
	if platform == "xtool" {
		return filepath.Join(buildDir, "Sources", "Runner")
	}
	return filepath.Join(buildDir, "Runner")
}

func ensureAndroidRunnerSupport(cs *mutate.Changeset, buildDir string) ([]string, error) {
	root := filepath.Join(buildDir, "app", "src", "main", "java", "com", "drift", "runner")
	var changed []string
	for _, f := range AndroidRunnerSupportFiles {
		content, err := templates.ReadFile(f.TemplatePath)
		if err != nil {
			return changed, fmt.Errorf("read %s: %w", f.TemplatePath, err)
		}
		dest := filepath.Join(root, f.Name)
		paths, err := planFile(cs, dest, content)
		if err != nil {
			return changed, err
		}
		changed = append(changed, paths...)
	}
	return changed, nil
}

// planFile plans content at path, returning path if that changes it.
func planFile(cs *mutate.Changeset, path string, content []byte) ([]string, error) {
	changed, err := cs.WriteFile(path, content)
	if err != nil {
		return nil, err
	}
	if !changed {
		return nil, nil
	}
	return []string{path}, nil
}
